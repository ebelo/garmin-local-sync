"""Outbound contracts owned by the application, implemented by infrastructure."""

from collections.abc import Iterable, Iterator, Sequence
from datetime import date
from typing import Protocol

from ..domain.models import (
    ActivityDetail,
    ActivityState,
    ActivitySummary,
    DateWindow,
    DecodedActivity,
    JsonValue,
)


class ActivitySource(Protocol):
    """Return domain values; translate transport failures into domain SourceError.

    Successful no-data health replies return None/empty JSON, never a failure.
    Pagination returns at most the requested number of summaries.
    """

    def list_activities(self, offset: int, limit: int, include_children: bool) -> list[ActivitySummary]: ...
    def activity_detail(self, activity_id: int) -> ActivityDetail: ...
    def download_activity(self, activity_id: int) -> bytes: ...
    def activity_workouts(self, activity_id: int) -> list[dict]: ...
    def health(self, dataset: str, window: DateWindow) -> JsonValue: ...
    def context(self) -> Iterator[tuple[str, JsonValue]]: ...


class SyncRepository(Protocol):
    """Persistence contract, not a database connection or transaction manager.

    Activity states are newest first; response windows are sorted by start date.
    Saving responses/imports clears that item's previous failure atomically with
    its successful checkpoint. Import completion must follow both geographic and
    attribute persistence; interruption between stores must remain resumable.
    Raw responses, source observations and explicit segments must be retained.
    """

    def save_summaries(self, summaries: Iterable[ActivitySummary]) -> None: ...
    def activity_states(self, limit: int | None = None) -> Sequence[ActivityState]: ...
    def save_import(self, activity_id: int, detail: ActivityDetail, decoded: DecodedActivity) -> None: ...
    def earliest_activity_date(self) -> date | None: ...
    def first_wellness_date(self) -> date | None: ...
    def response_windows(self, dataset: str, start: str, end: str) -> Sequence[DateWindow]: ...
    def has_response(self, dataset: str, key: str) -> bool: ...
    def save_response(
        self, dataset: str, key: str, data: JsonValue, window: DateWindow | None = None
    ) -> None: ...
    def has_failure(self, task: str) -> bool: ...
    def record_failure(self, task: str, error: Exception) -> None: ...
    def clear_failure(self, task: str) -> None: ...
    def snapshot(self) -> dict: ...


class ArchiveStore(Protocol):
    """Return None only for an absent archive; writes must be atomic and private."""

    def read(self, activity_id: int) -> bytes | None: ...
    def write(self, activity_id: int, content: bytes) -> None: ...


class ActivityDecoder(Protocol):
    """Preserve source order/fields/segments; raise domain DecodeError on bad files."""

    def decode(self, content: bytes, activity_id: int) -> DecodedActivity: ...


class Progress(Protocol):
    def __call__(self, message: str) -> None: ...
